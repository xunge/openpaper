#!/usr/bin/env bash
# Render server/.env, jobs/.env and client/.env.local from deploy.env.
set -euo pipefail
source "$(dirname -- "$0")/lib.sh"

require_env_file
load_env

for name in SERVER_IP DEEPSEEK_API_KEY; do require_var "$name"; done

server_env="$ROOT_DIR/server/.env"
jobs_env="$ROOT_DIR/jobs/.env"
client_env="$ROOT_DIR/client/.env.local"
force="${FORCE_ENV:-0}"

# Reuse a secret that was generated previously, otherwise generate one and
# persist it into deploy.env so server and jobs never drift.
if [[ -z "${JOBS_INTERNAL_SECRET:-}" ]]; then
  for file in "$server_env" "$jobs_env"; do
    if [[ -f "$file" ]]; then
      value="$(grep -E '^JOBS_INTERNAL_SECRET=' "$file" | tail -1 | cut -d= -f2- || true)"
      [[ -n "$value" ]] && JOBS_INTERNAL_SECRET="$value"
    fi
  done
fi
if [[ -z "${JOBS_INTERNAL_SECRET:-}" ]]; then
  JOBS_INTERNAL_SECRET="$(gen_secret)"
  if [[ "$DRY_RUN" != "1" ]]; then
    printf '\n# generated by scripts/deploy/50-init-env.sh\nJOBS_INTERNAL_SECRET=%s\n' "$JOBS_INTERNAL_SECRET" >> "$DEPLOY_ENV"
    chmod 600 "$DEPLOY_ENV"
  fi
fi
export JOBS_INTERNAL_SECRET

client_domain="$(normalize_url "${CLIENT_DOMAIN:-http://${SERVER_IP}}")"
api_domain="$(normalize_url "${API_DOMAIN:-http://${SERVER_IP}:${SERVER_PORT:-8100}}")"
minio_port="${MINIO_PORT:-9000}"
s3_endpoint="$(normalize_url "${S3_ENDPOINT_URL:-http://${SERVER_IP}:${minio_port}}")"
s3_bucket="${S3_BUCKET_NAME:-openpaper}"
s3_public="$(normalize_url "${S3_PUBLIC_URL:-${s3_endpoint}/${s3_bucket}}")"
server_port="${SERVER_PORT:-8100}"
jobs_port="${JOBS_PORT:-8101}"
mineru_fileparse="${MINERU_FILE_PARSE_URL:-http://host.docker.internal:8003}"
mineru_tasks="${MINERU_TASKS_API_URL:-http://host.docker.internal:8000}"
deepseek_base="${DEEPSEEK_BASE_URL:-https://api.deepseek.com/v1}"
deepseek_model="${DEEPSEEK_DEFAULT_MODEL:-deepseek-chat}"
deepseek_fast="${DEEPSEEK_FAST_MODEL:-$deepseek_model}"
postgres_password="${POSTGRES_PASSWORD:-postgres}"

if [[ "$s3_endpoint" == *"minio:9000"* ]]; then
  die "S3_ENDPOINT_URL must be browser/container reachable, not minio:9000"
fi

write_file() {
  local path="$1"
  if [[ -f "$path" && "$force" != "1" ]]; then
    warn "keeping existing $path (set FORCE_ENV=1 to overwrite)"
    return 0
  fi
  if [[ "$DRY_RUN" == "1" ]]; then
    log "would write $path"
  else
    mkdir -p "$(dirname "$path")"
    cat > "$path"
    chmod 600 "$path"
    ok "wrote $path"
  fi
}

log "rendering server/.env"
write_file "$server_env" <<EOF
DEBUG=False
DATABASE_URL=postgresql://postgres:${postgres_password}@postgres:5432/annotated-paper

DEFAULT_LLM_PROVIDER=deepseek
DEEPSEEK_API_KEY=${DEEPSEEK_API_KEY}
DEEPSEEK_BASE_URL=${deepseek_base}
DEEPSEEK_DEFAULT_MODEL=${deepseek_model}
DEEPSEEK_FAST_MODEL=${deepseek_fast}

AWS_ACCESS_KEY_ID=${AWS_ACCESS_KEY_ID:-minioadmin}
AWS_SECRET_ACCESS_KEY=${AWS_SECRET_ACCESS_KEY:-minioadmin}
AWS_REGION=${AWS_REGION:-us-east-1}
S3_BUCKET_NAME=${s3_bucket}
S3_ENDPOINT_URL=${s3_endpoint}
S3_PUBLIC_URL=${s3_public}

CELERY_BROKER_URL=pyamqp://guest:guest@rabbitmq:5672//
CELERY_API_URL=http://jobs-api:8001
WEBHOOK_BASE_URL=http://server:8000
JOBS_INTERNAL_SECRET=${JOBS_INTERNAL_SECRET}

CLIENT_DOMAIN=${client_domain}
API_DOMAIN=${api_domain}
SESSION_COOKIE_DOMAIN=

UNLIMITED_USAGE=${UNLIMITED_USAGE:-true}
MAX_UPLOAD_SIZE_MB=${MAX_UPLOAD_SIZE_MB:-200}
ALLOW_LOCAL_REGISTRATION=${ALLOW_LOCAL_REGISTRATION:-true}

OCR_PROVIDER=mineru
MINERU_FILE_PARSE_URL=${mineru_fileparse}
MINERU_TASKS_API_URL=${mineru_tasks}
MINERU_API_MODE=${MINERU_API_MODE:-auto}
MINERU_TIER=${MINERU_TIER:-standard}
MINERU_OCR_MODE=${MINERU_OCR_MODE:-auto}
MINERU_PRESERVE_VISUAL_BLOCKS=${MINERU_PRESERVE_VISUAL_BLOCKS:-true}
MINERU_VISUAL_BLOCK_TYPES=${MINERU_VISUAL_BLOCK_TYPES:-table,algorithm,code}

EXPORT_MAX_ASSET_MB=${EXPORT_MAX_ASSET_MB:-64}
EXPORT_MAX_TOTAL_MB=${EXPORT_MAX_TOTAL_MB:-512}
EXPORT_PANDOC_TIMEOUT=${EXPORT_PANDOC_TIMEOUT:-120}
EXPORT_PANDOC_CONCURRENCY=${EXPORT_PANDOC_CONCURRENCY:-2}
EXPORT_REFERENCE_DOC=/app/templates/academic-reference.docx
EOF

log "rendering jobs/.env"
write_file "$jobs_env" <<EOF
DEBUG=False
SERVICE_NAME=jobs
LOG_LEVEL=${LOG_LEVEL:-INFO}

DEFAULT_LLM_PROVIDER=deepseek
DEEPSEEK_API_KEY=${DEEPSEEK_API_KEY}
DEEPSEEK_BASE_URL=${deepseek_base}
DEEPSEEK_DEFAULT_MODEL=${deepseek_model}
DEEPSEEK_FAST_MODEL=${deepseek_fast}

AWS_ACCESS_KEY_ID=${AWS_ACCESS_KEY_ID:-minioadmin}
AWS_SECRET_ACCESS_KEY=${AWS_SECRET_ACCESS_KEY:-minioadmin}
AWS_REGION=${AWS_REGION:-us-east-1}
S3_BUCKET_NAME=${s3_bucket}
S3_ENDPOINT_URL=${s3_endpoint}
S3_PUBLIC_URL=${s3_public}

CELERY_BROKER_URL=pyamqp://guest:guest@rabbitmq:5672//
CELERY_RESULT_BACKEND=redis://redis:6379/0
WEBHOOK_BASE_URL=http://server:8000
JOBS_INTERNAL_SECRET=${JOBS_INTERNAL_SECRET}

OCR_PROVIDER=mineru
MINERU_FILE_PARSE_URL=${mineru_fileparse}
MINERU_TASKS_API_URL=${mineru_tasks}
MINERU_API_MODE=${MINERU_API_MODE:-auto}
MINERU_TIER=${MINERU_TIER:-standard}
MINERU_OCR_MODE=${MINERU_OCR_MODE:-auto}
MINERU_PRESERVE_VISUAL_BLOCKS=${MINERU_PRESERVE_VISUAL_BLOCKS:-true}
MINERU_VISUAL_BLOCK_TYPES=${MINERU_VISUAL_BLOCK_TYPES:-table,algorithm,code}
MINERU_DPI=${MINERU_DPI:-300}
MINERU_MAX_PDF_MB=${MINERU_MAX_PDF_MB:-100}
MINERU_MAX_ZIP_MB=${MINERU_MAX_ZIP_MB:-512}
MINERU_TASK_TIMEOUT=${MINERU_TASK_TIMEOUT:-1800}

TRANSLATE_MODEL=${TRANSLATE_MODEL:-$deepseek_fast}
TRANSLATE_CHUNK_CHARS=${TRANSLATE_CHUNK_CHARS:-6000}
TRANSLATE_WORKERS=${TRANSLATE_WORKERS:-6}
EOF

log "rendering client/.env.local"
write_file "$client_env" <<EOF
NEXT_PUBLIC_API_URL=${NEXT_PUBLIC_API_URL:-}
EOF

if [[ -n "${TTS_BASE_URL:-}" ]]; then
  log "TTS is enabled; append TTS variables to server/.env"
  if [[ "$DRY_RUN" != "1" ]]; then
    {
      echo "TTS_BASE_URL=${TTS_BASE_URL}"
      echo "TTS_MODEL=${TTS_MODEL:-Qwen3-TTS-12Hz-1.7B-CustomVoice}"
      echo "TTS_MAX_CHUNK_CHARS=${TTS_MAX_CHUNK_CHARS:-800}"
    } >> "$server_env"
  fi
fi

ok "environment files rendered"
log "server: $server_env"
log "jobs:   $jobs_env"
log "client: $client_env"
